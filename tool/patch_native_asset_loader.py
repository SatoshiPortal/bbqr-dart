#!/usr/bin/env python3
"""Restore the Native Assets default after FRB 2.13 code generation."""
from pathlib import Path
import sys

path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("lib/src/rust/frb_generated.dart")
source = path.read_text()
version = "// @generated by `flutter_rust_bridge`@ 2.13.0."
anchor = "import 'package:flutter_rust_bridge/flutter_rust_bridge_for_generated.dart';"
loader = "import 'native_asset_library.dart'\n    if (dart.library.js_interop) 'native_asset_library_web.dart';"
old = "      externalLibrary: externalLibrary,"
new = "      externalLibrary: externalLibrary ?? nativeAssetLibrary(),"
if version not in source or source.count(anchor) != 1:
    raise SystemExit("Unexpected FRB output; inspect the new generated bridge")
if source.count(loader) == 1 and source.count(new) == 1 and old not in source:
    raise SystemExit(0)
if loader in source or new in source or source.count(old) != 1:
    raise SystemExit("Partially patched or changed FRB output; inspect manually")
source = source.replace(anchor, anchor + "\n" + loader).replace(old, new)
path.write_text(source)
